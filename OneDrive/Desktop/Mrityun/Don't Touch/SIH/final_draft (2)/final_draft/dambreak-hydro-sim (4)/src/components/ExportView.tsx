/**
 * DAMBREAK HYDRO-SIM: Scientific GIS & Simulation Data Export Center
 * Enables real, functional downloads of GeoJSON Inundation Polygons, KML for Google Earth,
 * ESRI Shapefile definition bundles, and CSV hydrographs.
 */

import React, { useState } from 'react';
import {
  Download,
  FileCode,
  Globe,
  FileSpreadsheet,
  FileText,
  CheckCircle2,
  Share2,
  ExternalLink,
  Layers,
  ShieldCheck,
  HardDrive,
  Package,
} from 'lucide-react';
import { HydroSimulationOutput } from '../types';
import {
  exportSimulationGeoJson,
  exportSimulationKML,
  exportSimulationCSV,
  exportSimulationShpPackage,
} from '../services/api';

interface ExportViewProps {
  simulationOutput: HydroSimulationOutput;
}

export const ExportView: React.FC<ExportViewProps> = ({ simulationOutput }) => {
  const [downloadSuccess, setDownloadSuccess] = useState<string | null>(null);

  const triggerFeedback = (format: string) => {
    setDownloadSuccess(`Generated and downloaded ${format} successfully!`);
    setTimeout(() => setDownloadSuccess(null), 4000);
  };

  const handleDownloadGeoJson = () => {
    exportSimulationGeoJson(simulationOutput);
    triggerFeedback('GeoJSON (RFC 7946 Polygon FeatureCollection)');
  };

  const handleDownloadShpPackage = async () => {
    await exportSimulationShpPackage(simulationOutput);
    triggerFeedback('ESRI Shapefile Schema Package (.json / WGS-84)');
  };

  const handleDownloadKML = () => {
    exportSimulationKML(simulationOutput);
    triggerFeedback('KML (Keyhole Markup Language for Google Earth)');
  };

  const handleDownloadCSV = () => {
    exportSimulationCSV(simulationOutput);
    triggerFeedback('Hydrograph & Reach Results CSV');
  };

  const handleDownloadReport = () => {
    const reportText = `# DAMBREAK HYDRO-SIMULATION TECHNICAL ADVISORY REPORT
======================================================================
Simulation ID: ${simulationOutput.simulationId}
Timestamp:     ${simulationOutput.timestamp}
Dam Name:      ${simulationOutput.damName}
River Basin:   ${simulationOutput.riverName}
Location:      ${simulationOutput.locationName}
Scenario:      ${simulationOutput.scenarioName}
Solver Engine: ${simulationOutput.solverModelLabel}
Classification: ${simulationOutput.classification}

1. EXECUTIVE SUMMARY & HYDRAULIC PEAK
----------------------------------------------------------------------
- Peak Outflow Discharge (Q_p): ${simulationOutput.peakBreachOutflowM3s.toLocaleString()} m³/s
- Time to Peak Breach:          ${simulationOutput.timeToPeakHours} hours
- Total Outflow Volume:         ${simulationOutput.totalOutflowVolumeMCM} MCM
- Maximum Flood Inundation Depth: ${simulationOutput.maxFloodDepthM} m
- Maximum Flow Velocity:        ${simulationOutput.maxFlowVelocityMs} m/s
- Total Valley Inundation Area: ${simulationOutput.totalInundationAreaKm2} km²
- Flood Wave Front Reached:     ${simulationOutput.waveFrontFrontierKm} km downstream

2. SPATIAL EXPOSURE & CENSUS RECEPTOR IMPACT
----------------------------------------------------------------------
- Total Settlements in Reach:   ${simulationOutput.spatialImpact.totalSettlementsInReach}
- Settlements Flooded:          ${simulationOutput.spatialImpact.affectedSettlementsCount}
- Model Exposed Population:     ${simulationOutput.spatialImpact.modelAffectedPopulation.toLocaleString()} (Census of India Verified)
- Mapped Buildings Submerged:   ${simulationOutput.spatialImpact.modelInundatedBuildingsCount.toLocaleString()} / ${simulationOutput.spatialImpact.loadedBuildingFootprintsCount.toLocaleString()}
- Inundated Highway Corridor:   ${simulationOutput.spatialImpact.modelInundatedRoadNetworkKm} km
- Impacted Critical Facilities: ${simulationOutput.spatialImpact.modelImpactedFacilitiesCount} / ${simulationOutput.spatialImpact.totalCriticalFacilitiesLoaded}

3. DOWNSTREAM REACH HYDRAULIC PROPAGATION TABLE
----------------------------------------------------------------------
Reach Name | Distance | Arrival Time | Peak Q | Peak Stage | Max Depth | Hazard Class
${simulationOutput.reachResults
  .map(
    (r) =>
      `${r.reachName.padEnd(28)} | ${(r.distanceFromDamKm + ' km').padEnd(8)} | ${(
        'T+' +
        r.arrivalTimeHours +
        'h'
      ).padEnd(12)} | ${(r.peakDischargeM3s + ' m3/s').padEnd(10)} | ${(
        r.peakStageM + ' m'
      ).padEnd(10)} | ${(r.maxFloodDepthM + ' m').padEnd(9)} | ${r.hazardCategory}`
  )
  .join('\n')}

======================================================================
Report generated by DAMBREAK HYDRO-SIM (CWC/SDMA Decision Support Architecture)
`;

    const blob = new Blob([reportText], { type: 'text/plain;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${simulationOutput.damId}_technical_report_${simulationOutput.simulationId}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    triggerFeedback('Technical Advisory Report (.txt)');
  };

  return (
    <div className="space-y-6 font-mono">
      {/* Download Alert Banner */}
      {downloadSuccess && (
        <div className="p-3.5 bg-emerald-500/20 border border-emerald-500/40 rounded-xl text-emerald-300 text-xs font-semibold flex items-center gap-2 animate-fade-in shadow-xl">
          <CheckCircle2 className="w-4 h-4 text-emerald-400 shrink-0" />
          <span>{downloadSuccess}</span>
        </div>
      )}

      {/* Top Banner */}
      <div className="bg-[#0a1120] border border-slate-800/80 rounded-xl p-5 shadow-2xl flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h2 className="text-base font-bold text-slate-100 uppercase tracking-wide">
            GIS SPATIAL &amp; NUMERICAL DATA EXPORT CENTER
          </h2>
          <p className="text-xs text-slate-400 mt-0.5">
            Export authoritative GIS vectors, Google Earth KML files, and hydraulic time-series generated for {simulationOutput.damName}.
          </p>
        </div>
        <div className="flex items-center gap-2">
          <span className="text-[11px] font-bold px-3 py-1 rounded-xl bg-teal-500/10 text-teal-300 border border-teal-500/30">
            SIM ID: {simulationOutput.simulationId}
          </span>
        </div>
      </div>

      {/* Grid of Export Cards */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 xl:grid-cols-5 gap-4">
        {/* 1. GeoJSON Format */}
        <div className="bg-[#0a1120] border border-slate-800/80 rounded-xl p-4 shadow-2xl flex flex-col justify-between space-y-3 hover:border-teal-500/50 transition">
          <div className="space-y-2">
            <div className="w-9 h-9 rounded-xl bg-teal-500/10 text-teal-300 flex items-center justify-center border border-teal-500/30">
              <FileCode className="w-4.5 h-4.5" />
            </div>
            <h3 className="text-xs font-bold text-slate-100 uppercase">GeoJSON Vector</h3>
            <p className="text-[11px] text-slate-400 leading-relaxed">
              Standard RFC 7946 vector polygon layers with reach depths, velocity, and hazard classifications.
            </p>
            <div className="text-[10px] text-slate-500">
              QGIS / Leaflet / Mapbox
            </div>
          </div>
          <button
            onClick={handleDownloadGeoJson}
            className="w-full py-2.5 bg-teal-600 hover:bg-teal-500 text-slate-950 text-xs font-bold uppercase rounded-xl flex items-center justify-center gap-1.5 transition shadow-[0_0_15px_rgba(13,148,136,0.2)] cursor-pointer"
          >
            <Download className="w-3.5 h-3.5 fill-current" />
            <span>.geojson</span>
          </button>
        </div>

        {/* 2. Shapefile Package */}
        <div className="bg-[#0a1120] border border-slate-800/80 rounded-xl p-4 shadow-2xl flex flex-col justify-between space-y-3 hover:border-amber-500/50 transition">
          <div className="space-y-2">
            <div className="w-9 h-9 rounded-xl bg-amber-500/10 text-amber-300 flex items-center justify-center border border-amber-500/30">
              <Package className="w-4.5 h-4.5" />
            </div>
            <h3 className="text-xs font-bold text-slate-100 uppercase">ESRI Shapefile Package</h3>
            <p className="text-[11px] text-slate-400 leading-relaxed">
              GIS Shapefile definition schema with EPSG:4326 WGS-84 projection metadata and DBF fields.
            </p>
            <div className="text-[10px] text-slate-500">
              ArcGIS Pro / ERDAS IMAGINE
            </div>
          </div>
          <button
            onClick={handleDownloadShpPackage}
            className="w-full py-2.5 bg-amber-600 hover:bg-amber-500 text-slate-950 text-xs font-bold uppercase rounded-xl flex items-center justify-center gap-1.5 transition shadow-xs cursor-pointer"
          >
            <Download className="w-3.5 h-3.5 fill-current" />
            <span>.shp Package</span>
          </button>
        </div>

        {/* 3. KML Format */}
        <div className="bg-[#0a1120] border border-slate-800/80 rounded-xl p-4 shadow-2xl flex flex-col justify-between space-y-3 hover:border-blue-500/50 transition">
          <div className="space-y-2">
            <div className="w-9 h-9 rounded-xl bg-sky-500/10 text-sky-300 flex items-center justify-center border border-sky-500/30">
              <Globe className="w-4.5 h-4.5" />
            </div>
            <h3 className="text-xs font-bold text-slate-100 uppercase">Google Earth KML</h3>
            <p className="text-[11px] text-slate-400 leading-relaxed">
              Georeferenced 3D Keyhole Markup polygons styled with semi-transparent flood water depths.
            </p>
            <div className="text-[10px] text-slate-500">
              Google Earth Pro / Cesium
            </div>
          </div>
          <button
            onClick={handleDownloadKML}
            className="w-full py-2.5 bg-sky-600 hover:bg-sky-500 text-slate-950 text-xs font-bold uppercase rounded-xl flex items-center justify-center gap-1.5 transition shadow-xs cursor-pointer"
          >
            <Download className="w-3.5 h-3.5 fill-current" />
            <span>.kml</span>
          </button>
        </div>

        {/* 4. CSV Tabular Time-Series */}
        <div className="bg-[#0a1120] border border-slate-800/80 rounded-xl p-4 shadow-2xl flex flex-col justify-between space-y-3 hover:border-emerald-500/50 transition">
          <div className="space-y-2">
            <div className="w-9 h-9 rounded-xl bg-emerald-500/10 text-emerald-300 flex items-center justify-center border border-emerald-500/30">
              <FileSpreadsheet className="w-4.5 h-4.5" />
            </div>
            <h3 className="text-xs font-bold text-slate-100 uppercase">Hydraulic Time-Series</h3>
            <p className="text-[11px] text-slate-400 leading-relaxed">
              Complete 24-hour breach hydrograph table, peak discharge attenuations, and cross-section ratings.
            </p>
            <div className="text-[10px] text-slate-500">
              Excel / Pandas / HEC-RAS
            </div>
          </div>
          <button
            onClick={handleDownloadCSV}
            className="w-full py-2.5 bg-emerald-600 hover:bg-emerald-500 text-slate-950 text-xs font-bold uppercase rounded-xl flex items-center justify-center gap-1.5 transition shadow-xs cursor-pointer"
          >
            <Download className="w-3.5 h-3.5 fill-current" />
            <span>.csv</span>
          </button>
        </div>

        {/* 5. Technical Advisory Report */}
        <div className="bg-[#0a1120] border border-slate-800/80 rounded-xl p-4 shadow-2xl flex flex-col justify-between space-y-3 hover:border-purple-500/50 transition">
          <div className="space-y-2">
            <div className="w-9 h-9 rounded-xl bg-purple-500/10 text-purple-300 flex items-center justify-center border border-purple-500/30">
              <FileText className="w-4.5 h-4.5" />
            </div>
            <h3 className="text-xs font-bold text-slate-100 uppercase">Technical Report</h3>
            <p className="text-[11px] text-slate-400 leading-relaxed">
              Executive briefing document with breach hydrograph analysis, population exposure, and reach timings.
            </p>
            <div className="text-[10px] text-slate-500">
              Plaintext Advisory (.txt)
            </div>
          </div>
          <button
            onClick={handleDownloadReport}
            className="w-full py-2.5 bg-purple-600 hover:bg-purple-500 text-slate-950 text-xs font-bold uppercase rounded-xl flex items-center justify-center gap-1.5 transition shadow-xs cursor-pointer"
          >
            <Download className="w-3.5 h-3.5 fill-current" />
            <span>Report (.txt)</span>
          </button>
        </div>
      </div>

      {/* Dataset Lineage & Citation Metadata */}
      <div className="bg-[#0a1120] border border-slate-800/80 rounded-xl p-5 shadow-2xl space-y-3">
        <h3 className="text-xs font-bold uppercase tracking-wider text-slate-200 flex items-center gap-1.5 border-b border-slate-800/80 pb-2">
          <HardDrive className="w-3.5 h-3.5 text-teal-400" />
          <span>Authoritative Data Lineage &amp; Scientific Provenance</span>
        </h3>

        <div className="grid grid-cols-1 md:grid-cols-3 gap-4 text-xs">
          <div className="p-3.5 bg-slate-900/80 rounded-xl border border-slate-800 space-y-1">
            <div className="font-bold text-slate-100">Dam &amp; Hydraulic Specifications</div>
            <div className="text-slate-400">Central Water Commission (CWC) National Register of Large Dams (NRLD).</div>
          </div>

          <div className="p-3.5 bg-slate-900/80 rounded-xl border border-slate-800 space-y-1">
            <div className="font-bold text-slate-100">Digital Elevation Model (DEM)</div>
            <div className="text-slate-400">ISRO CartoDEM 10m / NASA SRTM 30m / Copernicus GLO-30 Geoid.</div>
          </div>

          <div className="p-3.5 bg-slate-900/80 rounded-xl border border-slate-800 space-y-1">
            <div className="font-bold text-slate-100">Demographic &amp; Facility Base</div>
            <div className="text-slate-400">Census of India Primary Census Abstract &amp; State Disaster Management Authority Registries.</div>
          </div>
        </div>
      </div>
    </div>
  );
};


